import { expect } from '@playwright/test';
import { electron } from './electron.mjs';
import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { tmpdir, cpus, platform, arch, release } from 'node:os';
import { createHash } from 'node:crypto';
const root = resolve(import.meta.dirname, '../..');
const out = resolve(root, 'test-results/content-reader');
const temp = await mkdtemp(resolve(tmpdir(), 'pero-content-e2e-'));
await mkdir(out, {recursive:true});
const source = '[\n'+Array.from({length:8000}, (_,i)=>`{"id":${9007199254740993n+BigInt(i)},"label":"中文 row ${i}","amount":1.0000000000000000001,"data":{"ok":true,"text":"${'x'.repeat(25)}"}}`).join(',\n')+'\n]';
