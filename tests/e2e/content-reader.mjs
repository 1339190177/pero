const env={...process.env,PERO_DESKTOP_DATA_DIR:resolve(temp,'desktop'),PERO_LOCALE:'en',PERO_APPS_ROOT:resolve(temp,'apps'),PERO_SETTINGS_PATH:resolve(temp,'settings.json'),PERO_HISTORY_PATH:resolve(temp,'history.jsonl'),PERO_AGENTS_FILE:agents};
delete env.ELECTRON_RUN_AS_NODE;
const errors=[];
const app=await electron.launch({args:['--use-mock-keychain',resolve(root,'desktop')],cwd:root,env});
let page;
try {
 page=await app.firstWindow();
 page.on('pageerror',e=>errors.push(e.message));
 await page.waitForFunction(()=>window.peroDiagnostics&&JSON.parse(window.peroDiagnostics.snapshot()).connected&&!document.getElementById('loading'),undefined,{timeout:60000});
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1488,1086));
 const state=()=>page.evaluate(()=>JSON.parse(window.peroDiagnostics.snapshot()));
 await expect.poll(async()=>(await state()).agents?.some(a=>a.id==='fixture')).toBe(true);
 await page.mouse.click(100,28);
 await expect.poll(async()=>(await state()).chats.length).toBe(1);
 const {height}=await page.evaluate(()=>({height:innerHeight}));
 await page.mouse.click(1240,height-20);
 await page.keyboard.press('ArrowUp');await page.keyboard.press('Enter');
 await expect.poll(async()=>(await state()).chats[0].agent).toBe('fixture');
 await page.mouse.click(800,height-75);
 await page.keyboard.type('contentview');
 await expect.poll(async()=>(await state()).composer).toBe('contentview');
 await page.keyboard.press('Enter');
 await expect.poll(async()=>(await state()).chats[0].tools?.length,{timeout:15000}).toBe(1);
 await expect.poll(async()=>(await state()).chats[0].state).toBe('idle');
 await page.screenshot({scale:'css',path:resolve(out,'collapsed.png')});
 await page.evaluate(()=>{window.__contentLongTasks=[];new PerformanceObserver(list=>window.__contentLongTasks.push(...list.getEntries().map(e=>({start:e.startTime,duration:e.duration})))).observe({type:'longtask',buffered:false});});
 const start=await page.evaluate(()=>performance.now());
 await page.mouse.click(500,169);
 await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
 const elapsed=await page.evaluate(()=>performance.now());
 await expect.poll(async()=>(await state()).contentReaders.length).toBe(1);
 await page.screenshot({scale:'css',path:resolve(out,'preview.png')});
 const sourceStart=await page.evaluate(()=>performance.now());
 await page.mouse.click(392,205);
 await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
 const sourceEnd=await page.evaluate(()=>performance.now());
 await expect.poll(async()=>(await state()).contentReaders[0]?.source).toBe(true);
 await page.screenshot({scale:'css',path:resolve(out,'source.png')});
 console.log(JSON.stringify({sourceMs:sourceEnd-sourceStart}));
 console.log(JSON.stringify({openMs:elapsed-start,longTasks:await page.evaluate(()=>window.__contentLongTasks),readers:(await state()).contentReaders}));
 console.log(JSON.stringify({bytes:Buffer.byteLength(source),readers:(await state()).contentReaders, viewport:await page.evaluate(()=>({width:innerWidth,height:innerHeight}))}));
 if(process.argv.includes('--pilot')) { await writeFile(resolve(out,'pilot.json'),JSON.stringify({temp,errors})); }
} catch(error) { if(page) { await page.screenshot({scale:'css',path:resolve(out,'failure.png')}); await writeFile(resolve(out,'failure.json'),await page.evaluate(()=>window.peroDiagnostics.snapshot())); } throw error; } finally { if(page&&errors.length) console.error(errors);await app.close(); }
